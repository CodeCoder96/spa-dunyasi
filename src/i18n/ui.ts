export type UiKey = keyof typeof ui;

export function t(lang: Lang, key: UiKey, vars?: Record<string, string | number>): string {
  let s: string = ui[key][lang];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** Date format (ICR-16): TR "3 Ekim 2026", EN "3 October 2026". */
export function formatDate(lang: Lang, iso: string): string {
  const d = new Date(`${iso.slice(0, 10)}T12:00:00Z`);
  return new Intl.DateTimeFormat(lang === 'tr' ? 'tr-TR' : 'en-GB', { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' }).format(d);
}

const escapeHtml = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/** Escape text and wrap brand names in translate="no" (TAS-11). Use with set:html. */
export function brandHtml(s: string): string {
  return escapeHtml(s).replace(/(Spa Dünyası|Spa World)/g, '<span translate="no">$1</span>');
}
